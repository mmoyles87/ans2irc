//! Code page 437 as DOS drew it, including glyphs for the control range.

const LOW: [char; 32] = [
    ' ', '☺', '☻', '♥', '♦', '♣', '♠', '•', '◘', '○', '◙', '♂', '♀', '♪', '♫', '☼', //
    '►', '◄', '↕', '‼', '¶', '§', '▬', '↨', '↑', '↓', '→', '←', '∟', '↔', '▲', '▼',
];

const HIGH: [char; 128] = [
    'Ç', 'ü', 'é', 'â', 'ä', 'à', 'å', 'ç', 'ê', 'ë', 'è', 'ï', 'î', 'ì', 'Ä', 'Å', //
    'É', 'æ', 'Æ', 'ô', 'ö', 'ò', 'û', 'ù', 'ÿ', 'Ö', 'Ü', '¢', '£', '¥', '₧', 'ƒ', //
    'á', 'í', 'ó', 'ú', 'ñ', 'Ñ', 'ª', 'º', '¿', '⌐', '¬', '½', '¼', '¡', '«', '»', //
    '░', '▒', '▓', '│', '┤', '╡', '╢', '╖', '╕', '╣', '║', '╗', '╝', '╜', '╛', '┐', //
    '└', '┴', '┬', '├', '─', '┼', '╞', '╟', '╚', '╔', '╩', '╦', '╠', '═', '╬', '╧', //
    '╨', '╤', '╥', '╙', '╘', '╒', '╓', '╫', '╪', '┘', '┌', '█', '▄', '▌', '▐', '▀', //
    'α', 'ß', 'Γ', 'π', 'Σ', 'σ', 'µ', 'τ', 'Φ', 'Θ', 'Ω', 'δ', '∞', 'φ', 'ε', '∩', //
    '≡', '±', '≥', '≤', '⌠', '⌡', '÷', '≈', '°', '∙', '·', '√', 'ⁿ', '²', '■', '\u{a0}',
];

/// A CP437 byte as it appeared on screen.
pub fn glyph(byte: u8) -> char {
    match byte {
        0x00..=0x1f => LOW[byte as usize],
        0x7f => '⌂',
        0x20..=0x7e => byte as char,
        _ => HIGH[(byte - 0x80) as usize],
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn blocks_and_shades() {
        assert_eq!(glyph(0xdb), '█');
        assert_eq!(glyph(0xdc), '▄');
        assert_eq!(glyph(0xdf), '▀');
        assert_eq!(glyph(0xb0), '░');
        assert_eq!(glyph(0x41), 'A');
        assert_eq!(glyph(0x03), '♥');
    }
}
